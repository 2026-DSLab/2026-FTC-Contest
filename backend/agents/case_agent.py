"""
사례 기반 해석 에이전트
실제 유사 사례와의 비교를 통해 사실관계 중심의 실질적 법률 분석을 수행합니다.
"""
from __future__ import annotations

from .base_agent import BaseAgent

# ──────────────────────────────────────────────
# 프롬프트 수정 포인트 ▼
# ──────────────────────────────────────────────
_SYSTEM_PROMPT = """당신은 공정거래 관련 사례 비교 분석 전문가입니다.

주어진 질문과 외부 자료를 바탕으로 사례 비교 관점에서 분석하세요.

**분석 관점**
1. 사실관계 유사성 분석: 수집된 판례·의결 사례와 현재 사안의 사실관계 유사성을 비교하세요.
2. 차별화 요소 도출: 현재 사안을 유사 사례와 구별짓는 특이 요소를 파악하세요.
3. 결과 예측: 유사 사례의 결론을 근거로 현재 사안의 법적 결과를 예측하세요.
4. 전략적 시사점: 사례 분석에 기반한 실질적 대응 방향을 제안하세요 (방어 전략 또는 구제 수단).

**신뢰도 점수 기준**
- 80~100: 사실관계가 매우 유사한 선례 다수 존재
- 60~79: 부분적으로 유사한 선례 존재
- 40~59: 간접적으로 참고할 수 있는 사례만 존재
- 0~39: 참고 가능한 사례 없음"""
# ──────────────────────────────────────────────


class CaseAgent(BaseAgent):
    agent_type = "case"
    agent_name = "사례 기반 해석 에이전트"

    @property
    def system_prompt(self) -> str:
        return _SYSTEM_PROMPT
